def generate_alipay() -> Path:
    content = "\n".join(
        [
            "-----------------------------导出信息-----------------------------",
            "导出信息：",
            "姓名：测试用户",
            "起始时间：[2026-07-01 00:00:00]    终止时间：[2026-07-31 23:59:59]",
            "导出交易类型：[全部]",
            "共12笔记录",
            ALIPAY_HEADER,
            *ALIPAY_ROWS,
            "",
        ]
    )
    path = SAMPLES_DIR / "alipay_sample.csv"
    path.write_bytes(content.encode("gb18030"))
    return path


def generate_wechat() -> Path:
    path = SAMPLES_DIR / "wechat_sample.xlsx"
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append(["微信支付账单明细"])
    ws.append(["微信昵称：[测试用户]"])
    ws.append(["起始时间：[2026-07-01 00:00:00] 终止时间：[2026-07-31 23:59:59]"])
    ws.append(["导出类型：[全部]"])
    ws.append(["共5笔记录"])
    ws.append([None])
    ws.append(["----------------------微信支付账单明细列表--------------------"])
    ws.append(WECHAT_HEADER)
    for row in WECHAT_ROWS:
        ws.append(row)
    wb.save(path)
    return path


